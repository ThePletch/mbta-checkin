#!/usr/bin/env node
/**
 * Query MBTA /routes and /stops and emit TypeScript string-literal unions
 * for IDs and display names.
 *
 * Usage: npm run generate:ids
 * Optional: MBTA_API_KEY=... for higher rate limits
 */
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const API_BASE = 'https://api-v3.mbta.com';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_FILE = path.join(ROOT, 'js/lib/generated/mbta-entities.d.ts');
const PAGE_LIMIT = 1000;
const USER_AGENT = 'mbta-checkin-typegen/1.0 (+https://github.com/spletcher/mbta-checkin)';

/**
 * @param {string} pathname
 * @param {Record<string, string>} [query]
 */
async function fetchJsonApi(pathname, query = {}) {
  const url = new URL(pathname, API_BASE);
  for (const [key, value] of Object.entries(query)) {
    url.searchParams.set(key, value);
  }

  /** @type {Record<string, string>} */
  const headers = {
    Accept: 'application/vnd.api+json, application/json',
    'User-Agent': USER_AGENT,
  };
  const apiKey = process.env.MBTA_API_KEY;
  if (apiKey) {
    headers['x-api-key'] = apiKey;
  }

  /** @type {unknown[]} */
  const items = [];
  let nextUrl = url.toString();

  while (nextUrl) {
    const response = await fetch(nextUrl, { headers });
    if (!response.ok) {
      throw new Error(`Failed to fetch ${nextUrl}: ${response.status} ${response.statusText}`);
    }
    const body = await response.json();
    if (!Array.isArray(body.data)) {
      throw new Error(`Unexpected response shape from ${nextUrl}`);
    }
    items.push(...body.data);
    nextUrl = body.links?.next ?? null;
  }

  return items;
}

/** @param {string} value */
function asLiteral(value) {
  return JSON.stringify(value);
}

/**
 * @param {Iterable<string>} values
 * @param {string} typeName
 * @param {string} description
 */
function unionType(values, typeName, description) {
  const sorted = [...new Set(values)].filter((v) => v !== '').sort((a, b) => a.localeCompare(b));
  if (sorted.length === 0) {
    return `/** ${description} */\nexport type ${typeName} = never;\n`;
  }
  const lines = sorted.map((v) => `  | ${asLiteral(v)}`);
  return [
    `/**`,
    ` * ${description}`,
    ` * (${sorted.length} values)`,
    ` */`,
    `export type ${typeName} =`,
    ...lines.map((line, i) => (i === lines.length - 1 ? `${line};` : line)),
    '',
  ].join('\n');
}

async function main() {
  console.log('Fetching /routes…');
  const routes = await fetchJsonApi('/routes', {
    'page[limit]': String(PAGE_LIMIT),
    'fields[route]': 'long_name,short_name',
  });

  console.log(`Fetching /stops (paginated, page size ${PAGE_LIMIT})…`);
  const stops = await fetchJsonApi('/stops', {
    'page[limit]': String(PAGE_LIMIT),
    'fields[stop]': 'name',
  });

  /** @type {string[]} */
  const routeIds = [];
  /** @type {string[]} */
  const routeLongNames = [];
  /** @type {string[]} */
  const routeShortNames = [];
  for (const route of routes) {
    if (typeof route.id === 'string') routeIds.push(route.id);
    const attrs = route.attributes ?? {};
    if (typeof attrs.long_name === 'string') routeLongNames.push(attrs.long_name);
    if (typeof attrs.short_name === 'string') routeShortNames.push(attrs.short_name);
  }

  /** @type {string[]} */
  const stopIds = [];
  /** @type {string[]} */
  const stopNames = [];
  for (const stop of stops) {
    if (typeof stop.id === 'string') stopIds.push(stop.id);
    const attrs = stop.attributes ?? {};
    if (typeof attrs.name === 'string') stopNames.push(attrs.name);
  }

  console.log(
    `Collected ${routeIds.length} routes, ${stopIds.length} stops ` +
      `(${new Set(stopNames).size} unique stop names)`,
  );

  const contents = [
    '/**',
    ' * This file is auto-generated by `npm run generate:ids`.',
    ' * Do not edit by hand — regenerate from the live MBTA /routes and /stops lists.',
    ` * Source: ${API_BASE}`,
    ` * Generated: ${new Date().toISOString()}`,
    ' */',
    '',
    unionType(routeIds, 'RouteId', 'Canonical route IDs from `GET /routes` (`data[].id`).'),
    unionType(
      routeLongNames,
      'RouteLongName',
      'Route long names from `GET /routes` (`data[].attributes.long_name`).',
    ),
    unionType(
      routeShortNames,
      'RouteShortName',
      'Route short names from `GET /routes` (`data[].attributes.short_name`). Empty values omitted.',
    ),
    unionType(stopIds, 'StopId', 'Canonical stop IDs from `GET /stops` (`data[].id`).'),
    unionType(
      stopNames,
      'StopName',
      'Stop display names from `GET /stops` (`data[].attributes.name`). Duplicates collapsed.',
    ),
  ].join('\n');

  await mkdir(path.dirname(OUT_FILE), { recursive: true });
  await writeFile(OUT_FILE, contents, 'utf8');
  console.log(`Wrote ${path.relative(ROOT, OUT_FILE)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
